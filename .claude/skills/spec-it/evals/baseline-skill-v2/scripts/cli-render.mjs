#!/usr/bin/env node
// Generates mockups/cli.html from mockups/transcripts.md, so the readable page and the runnable
// transcripts never drift apart. Never edit cli.html by hand; edit transcripts.md and rerun.
// Usage: node cli-render.mjs <unit dir>
// Zero dependencies; Node 18+.

import fs from "node:fs";
import path from "node:path";

const unitDir = process.argv[2];
if (!unitDir) {
  console.error("Usage: node cli-render.mjs <unit dir, e.g. spec-it/1-branch-tool>");
  process.exit(2);
}
const mockups = path.join(unitDir, "mockups");
const src = path.join(mockups, "transcripts.md");
if (!fs.existsSync(src)) {
  console.error(`Not found: ${src}`);
  process.exit(1);
}

const md = fs.readFileSync(src, "utf8").replace(/\r\n/g, "\n");
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const ids = (s, kind) => (s.match(new RegExp(`\\b(?:[A-Z][A-Z0-9]{1,7}-)?${kind}-\\d+\\b`, "g")) || []).join(" ");
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const humanize = (s) => s.replace(/[-_]+/g, " ").replace(/^\w/, (c) => c.toUpperCase());

const title = (md.match(/^#\s+(.+)$/m) || [null, "CLI"])[1].trim();

// Exit codes table, kept as rows of [code, meaning].
const exitSection = (md.split(/^##\s+Exit codes\s*$/m)[1] || "").split(/^##\s/m)[0];
const exitRows = [...exitSection.matchAll(/^\|\s*(\d+)\s*\|\s*([^|]+?)\s*\|/gm)].map((m) => [m[1], m[2]]);

// Commands: every "## " heading except Exit codes.
const commands = [];
for (const part of md.split(/^##\s+/m).slice(1)) {
  const [headLine, ...rest] = part.split("\n");
  if (/^Exit codes\s*$/.test(headLine)) continue;
  const [name, idText = ""] = headLine.split("·").map((s) => s.trim());
  const body = rest.join("\n");
  const purpose = (body.split(/^###\s/m)[0].trim().split("\n")[0] || "").trim();
  const transcripts = [];
  for (const t of body.split(/^###\s+/m).slice(1)) {
    const [tHead, ...tRest] = t.split("\n");
    const [state, tIds = ""] = tHead.split("·").map((s) => s.trim());
    const tBody = tRest.join("\n");
    const code = (tBody.match(/```console\n([\s\S]*?)```/) || [null, ""])[1];
    const note = tBody.replace(/```console\n[\s\S]*?```/g, "").trim();
    transcripts.push({ state, fr: ids(tIds, "FR"), ec: ids(tIds, "EC"), code, note });
  }
  commands.push({ name, fr: ids(idText, "FR"), purpose, transcripts });
}

function renderCode(code) {
  return code
    .replace(/\n$/, "")
    .split("\n")
    .map((line) => {
      if (line.startsWith("$ ")) return `<span class="prompt" aria-hidden="true">$</span> <span class="cmd">${esc(line.slice(2))}</span>`;
      if (line.startsWith("! ")) return `<span class="stderr">${esc(line.slice(2))}</span>`;
      const exit = line.match(/^\[exit (\d+)\]$/);
      if (exit) return `<span class="exit">exit ${exit[1]}</span>`;
      return esc(line);
    })
    .join("\n");
}

const nav = commands.map((c) => `<li><a href="#${slug(c.name)}"><code>${esc(c.name)}</code></a></li>`).join("\n        ");
const firstState = commands.flatMap((c) => c.transcripts)[0]?.state || "";

const sections = commands
  .map(
    (c) => `
    <section id="${slug(c.name)}" class="command" data-command="${esc(c.name)}"${c.fr ? ` data-fr="${c.fr}"` : ""}>
      <h2><code>${esc(c.name)}</code></h2>
      ${c.purpose ? `<p>${esc(c.purpose)}</p>` : ""}
${c.transcripts
  .map(
    (t) => `      <figure class="transcript" data-state="${esc(t.state)}"${t.ec ? ` data-ec="${t.ec}"` : ""}${t.fr ? ` data-fr="${t.fr}"` : ""}>
        <figcaption>${esc(humanize(t.state))}${t.ec ? ` <span class="ids">${t.ec}</span>` : ""}</figcaption>
        <pre><code>${renderCode(t.code)}</code></pre>${t.note ? `\n        <p class="note">${esc(t.note)}</p>` : ""}
      </figure>`
  )
  .join("\n")}
    </section>`
  )
  .join("\n");

const html = `<!doctype html>
<!-- Generated by spec-it scripts/cli-render.mjs from transcripts.md. Do not edit by hand. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${esc(title)}</title>
  <link rel="stylesheet" href="assets/theme.css">
  <style>
    .layout { display: grid; grid-template-columns: 14rem minmax(0, 1fr); gap: var(--space-6); max-width: 72rem; margin: 0 auto; padding: var(--space-6) var(--space-4); }
    nav ul { list-style: none; padding: 0; margin: 0; position: sticky; top: var(--space-4); }
    nav li { margin-bottom: var(--space-2); }
    .command { margin-bottom: var(--space-7); }
    .command h2 { margin-bottom: var(--space-2); }
    .transcript { margin: var(--space-4) 0; }
    .transcript figcaption { font-weight: 600; margin-bottom: var(--space-2); }
    .transcript .ids { font-weight: 400; color: var(--color-text-muted); font-size: var(--text-sm); margin-left: var(--space-2); }
    .transcript pre { margin: 0; padding: var(--space-4); border-radius: var(--radius-md); background: #16181d; color: #e8eaed; overflow-x: auto; font-family: var(--font-mono); font-size: var(--text-sm); line-height: 1.6; }
    .prompt { color: #8ab4f8; user-select: none; }
    .stderr { color: #ffb4a9; }
    .exit { display: inline-block; margin-top: var(--space-1); color: #c4c7c5; font-variant-numeric: tabular-nums; }
    .note { color: var(--color-text-muted); font-size: var(--text-sm); }
    table { max-width: 32rem; margin-bottom: var(--space-6); }
    th, td { text-align: left; padding: var(--space-2) var(--space-3); border-bottom: 1px solid var(--color-border); }
    @media (max-width: 48rem) { .layout { grid-template-columns: 1fr; } nav ul { position: static; } }
  </style>
</head>
<body data-states="all" data-default-state="${esc(firstState)}">
  <a class="skip-link" href="#main">Skip to content</a>
  <div class="layout">
    <nav aria-label="Commands">
      <ul>
        <li><a href="index.html">All artifacts</a></li>
        ${nav}
      </ul>
    </nav>
    <main id="main">
      <h1>${esc(title)}</h1>
      <p>Each transcript is also a test: <code>$</code> starts a command, red lines go to stderr, and the last line is the exit code.</p>
      <h2>Exit codes</h2>
      <table>
        <thead><tr><th scope="col">Code</th><th scope="col">Meaning</th></tr></thead>
        <tbody>
          ${exitRows.map(([c, m]) => `<tr><td class="num">${esc(c)}</td><td>${esc(m)}</td></tr>`).join("\n          ")}
        </tbody>
      </table>
${sections}
    </main>
  </div>
  <script src="assets/fixtures.js"></script>
  <script src="assets/app.js"></script>
</body>
</html>
`;

fs.writeFileSync(path.join(mockups, "cli.html"), html);
const count = commands.reduce((n, c) => n + c.transcripts.length, 0);
console.log(`Wrote ${path.join(mockups, "cli.html")}: ${commands.length} commands, ${count} transcripts.`);
